"""Write the reviewer-response experiment matrix and the commands that realise it.

Produces
    training/experiments.csv     one row per model: exp, selection, fraction,
                                 train_seed, xyz, out_dir
    training/make_training_sets.sh   make_masks.py calls that generate every
                                 pruned xyz the matrix needs (run on any machine
                                 that has DATA.xyz; CPU, minutes)
    training/jobs.txt            one `train_one.sh` command per line, for a
                                 Slurm/Flux job array on the GPU machine

Experiments (default settings; override with flags):
    E1 method   global_s0 / stratified_s0 / random_global_s0 / random_stratified_s0
                x fractions {0.05, 0.10, 0.20} x train seeds   -> R2 #2, R4 #3
    E2 fpsseed  global_s1 / stratified_s1 x same fractions x seeds -> R1 #4
    E3 full     100% x train seeds                                -> reference
    E4 adaptive per-group elbow-derived fractions (requires
                results/funiq/<sweep>/budget.json from pruning/elbow.py;
                skipped with a warning if absent)                 -> R2 #2

Usage:
    python training/make_experiment_matrix.py --data DATA.xyz [--seeds 0 1 2]
"""
import argparse
import csv
import json
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
STEM = "DS_2km6t3p8hxx2_0"


def pruned_name(sel_dir, frac):
    meta = json.load(open(REPO / "results/fps" / sel_dir / "fps_meta.json"))
    return f"{STEM}_{frac:.3f}_{meta['mode']}_s{meta['fps_seed']}.xyz"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", required=True, help="path to the labeled training xyz (with descriptors)")
    ap.add_argument("--seeds", type=int, nargs="+", default=[0, 1, 2])
    ap.add_argument("--fractions", type=float, nargs="+", default=[0.05, 0.10, 0.20])
    ap.add_argument("--out-root", default="results/models")
    ap.add_argument("--budget", default=None,
                    help="budget.json with per-group fractions for E4 (from pruning/elbow.py)")
    args = ap.parse_args()

    rows, mask_cmds = [], {}
    e1 = ["global_s0", "stratified_s0", "random_global_s0", "random_stratified_s0"]
    e2 = ["global_s1", "stratified_s1"]
    for exp, sels in (("E1_method", e1), ("E2_fpsseed", e2)):
        for sel in sels:
            if not (REPO / "results/fps" / sel / "fps_meta.json").exists():
                print(f"WARNING: results/fps/{sel} missing, skipping")
                continue
            mask_cmds.setdefault(sel, set()).update(args.fractions)
            for f in args.fractions:
                for s in args.seeds:
                    rows.append((exp, sel, f, s,
                                 f"results/pruned/{sel}/{pruned_name(sel, f)}",
                                 f"{args.out_root}/{exp}/{sel}/f{f:.3f}/seed{s}"))
    for s in args.seeds:
        rows.append(("E3_full", "none", 1.0, s, args.data, f"{args.out_root}/E3_full/seed{s}"))
    if args.budget and Path(args.budget).exists():
        for s in args.seeds:
            rows.append(("E4_adaptive", "stratified_s0", -1, s,
                         "results/pruned/adaptive_s0/" + f"{STEM}_adaptive_stratified_s0.xyz",
                         f"{args.out_root}/E4_adaptive/seed{s}"))
    else:
        print("NOTE: E4_adaptive skipped (no --budget file yet)")

    with open(REPO / "training/experiments.csv", "w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["exp", "selection", "fraction", "train_seed", "xyz", "out_dir"])
        w.writerows(rows)

    with open(REPO / "training/make_training_sets.sh", "w") as fh:
        fh.write("#!/bin/bash\n# generated by make_experiment_matrix.py -- run from repo root\nset -e\n"
                 f"DATA=${{DATA:-{args.data}}}   # override: DATA=/path/on/this/machine.xyz bash $0\n")
        for sel, fracs in sorted(mask_cmds.items()):
            fl = " ".join(f"{f:.3f}" for f in sorted(fracs))
            fh.write(f"python pruning/make_masks.py $DATA results/fps/{sel} results/pruned/{sel} "
                     f"--fractions {fl} --drop-descriptors\n")
        if args.budget and Path(args.budget).exists():
            fh.write(f"python pruning/make_masks.py $DATA results/fps/stratified_s0 results/pruned/adaptive_s0 "
                     f"--budget {args.budget} --drop-descriptors\n")

    with open(REPO / "training/jobs.txt", "w") as fh:
        for exp, sel, f, s, xyz, out in rows:
            fh.write(f"training/train_one.sh {xyz} {s} {out}\n")

    print(f"{len(rows)} models -> training/experiments.csv, training/jobs.txt, training/make_training_sets.sh")
    by = {}
    for r in rows:
        by[r[0]] = by.get(r[0], 0) + 1
    for k, v in by.items():
        print(f"  {k:12s} {v:4d} models")


if __name__ == "__main__":
    main()
